#!/usr/bin/env python3
"""Render board-measurement figures, or NOT RUN placeholders when empty.

Reads data/board/{turnaround,calls,throughput}.csv (see data/board/README)
and writes build/board-{turnaround,calls,throughput}.tex, each a complete
pgfplots axis. Model curves come from data/wire-cost.csv for comparison.
"""
import csv
import statistics
from pathlib import Path

root = Path(__file__).resolve().parents[2]
data, out = root / "doc/data", root / "doc/build"
out.mkdir(exist_ok=True)
TB = 10 / 115200
COMMON = (r"width=0.33\textwidth, height=42mm, tick label style={font=\scriptsize}, "
          r"label style={font=\scriptsize}, axis line style={cWire!45}, tick style={cWire!45}, "
          r"grid style={cWire!15}, clip=false, ")
PLACEHOLDER = (r"\node[align=center, font=\scriptsize\bfseries, text=cNone] at (rel axis cs:0.5,0.55) "
               r"{NOT RUN}; \node[align=center, font=\tiny, text=cNone, anchor=north] at (rel axis cs:0.5,0.45) "
               r"{awaiting board\\measurement in\\\texttt{data/board/%s}};")

def rows(name):
    with open(data / "board" / name) as f:
        return list(csv.DictReader(f))

def write(name, body):
    (out / f"board-{name}.tex").write_text("% generated by tools/board_data.py\n" + body + "\n")

# 1. turnaround tau: empirical CDF
r = rows("turnaround.csv")
axis = (r"\begin{tikzpicture}\begin{semilogxaxis}[" + COMMON +
        r"xlabel={turnaround $\tau$ ($\mu$s)}, ylabel={empirical CDF}, ymin=0, ymax=1, ytick={0,0.5,1}, "
        r"xmin=10, xmax=100000, xmajorgrids, ymajorgrids]")
if r:
    tau = sorted(max(1e-3, float(x["elapsed_us"]) - (int(x["tx_bytes"]) + int(x["rx_bytes"])) * TB * 1e6) for x in r)
    pts = " ".join(f"({t:.3f},{(i+1)/len(tau):.5f})" for i, t in enumerate(tau))
    axis += r"\addplot[const plot, thick, cBlockE] coordinates {" + pts + "};"
else:
    axis += PLACEHOLDER % "turnaround.csv"
write("turnaround", axis + r"\end{semilogxaxis}\end{tikzpicture}")

# 2. per-call time: measured median (if any) against the model at tau = 0 and 16 ms
wire = {(x["workload"], int(x["version"])): x for x in csv.DictReader(open(data / "wire-cost.csv"))}
names = ("vector", "dot", "scan", "matvec", "conv")
model = lambda w, v, tau: (int(wire[w, v]["tx_bytes"]) + int(wire[w, v]["rx_bytes"])) * TB * 1e3 + \
                          int(wire[w, v]["transactions"]) * tau * 1e3
r = rows("calls.csv")
axis = (r"\begin{tikzpicture}\begin{semilogyaxis}[" + COMMON +
        r"ylabel={time per call (ms)}, symbolic x coords={vector,dot,scan,matvec,conv}, xtick=data, "
        r"ymin=100, ymax=40000, ymajorgrids, enlarge x limits=0.15, "
        r"legend style={font=\tiny, at={(0.5,1.03)}, anchor=south, legend columns=3, draw=cWire!35, fill=white}]")
for v, mark, colour in ((2, "o", "cAluE"), (3, "square", "cBlockE")):
    for tau, style, tag in ((0.0, "solid", r"$\tau{=}0$"), (16e-3, "densely dashed", r"$\tau{=}16$\,ms")):
        pts = " ".join(f"({w},{model(w, v, tau):.2f})" for w in names)
        legend = rf"\addlegendentry{{model v{v}}}" if tau == 0 else ""
        axis += (rf"\addplot[{colour}, {style}, mark={mark}, mark options={{solid, fill=white}}"
                 rf"{'' if legend else ', forget plot'}] coordinates {{{pts}}}; {legend}")
if r:
    for v, colour in (("v2", "cAluE"), ("v3", "cBlockE")):
        med = {w: statistics.median(float(x["elapsed_ms"]) for x in r
                                    if x["workload"] == w and x["protocol"] == v) for w in names
               if any(x["workload"] == w and x["protocol"] == v for x in r)}
        pts = " ".join(f"({w},{t:.3f})" for w, t in med.items())
        axis += rf"\addplot[only marks, mark=*, {colour}] coordinates {{{pts}}}; \addlegendentry{{board {v}}}"
else:
    axis += r"\addlegendimage{empty legend}\addlegendentry{board: NOT RUN}"
axis += (r"\node[font=\tiny, text=cWire, anchor=north west] at (rel axis cs:0.02,0.97) "
         r"{dashed: $\tau=16$\,ms; solid: $\tau=0$};")
write("calls", axis + r"\end{semilogyaxis}\end{tikzpicture}")

# 3. throughput against a timed CPU baseline
r = rows("throughput.csv")
axis = (r"\begin{tikzpicture}\begin{loglogaxis}[" + COMMON +
        r"xlabel={elements $n$}, ylabel={elements per second}, xmin=10, xmax=10000, "
        r"ymin=10, ymax=1e9, ytick={1e2,1e4,1e6,1e8}, xmajorgrids, ymajorgrids, "
        r"legend style={font=\tiny, at={(0.03,0.97)}, anchor=north west, draw=cWire!35}]")
if r:
    for dev, colour, mark in (("cgra", "cBlockE", "square*"), ("cpu", "cAluE", "o")):
        for kern in sorted({x["kernel"] for x in r if x["device"] == dev}):
            by_n = {}
            for x in r:
                if x["device"] == dev and x["kernel"] == kern:
                    by_n.setdefault(int(x["n"]), []).append(float(x["elapsed_us"]))
            pts = " ".join(f"({n},{n / (statistics.median(t) * 1e-6):.6g})" for n, t in sorted(by_n.items()))
            axis += rf"\addplot[{colour}, mark={mark}] coordinates {{{pts}}}; \addlegendentry{{{dev} {kern}}}"
else:
    axis += PLACEHOLDER % "throughput.csv"
write("throughput", axis + r"\end{loglogaxis}\end{tikzpicture}")
