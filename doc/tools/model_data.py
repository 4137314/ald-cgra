#!/usr/bin/env python3
"""Derive MODEL curves from the archived counters (no new measurement).

Inputs: data/wire-cost.csv, data/scaling.csv (provenance checked by their own
renderers). Outputs in build/: latency-ratio.csv, roofline-*.csv,
utilization.csv and model-macros.tex. Every quantity here is a first-order
model (Section VII), never a timing measurement.
"""
import csv
import math
from pathlib import Path

root = Path(__file__).resolve().parents[2]
data, out = root / "doc/data", root / "doc/build"
out.mkdir(exist_ok=True)

BAUD, BITS_PER_BYTE = 115200, 10            # 8N1
TB = BITS_PER_BYTE / BAUD                   # seconds per byte on the wire
LINK = 1 / TB                               # bytes per second
FCLK, D, PES = 100e6, 2, 16                 # default build, Section IX
PEAK = PES * FCLK / D                       # PE operations per second

wire = {(r["workload"], int(r["version"])): r for r in csv.DictReader(open(data / "wire-cost.csv"))}
scal = {(r["experiment"], r["geometry"], r["kernel"], r["protocol"], int(r["n"]), int(r["repeat"])): r
        for r in csv.DictReader(open(data / "scaling.csv"))}
B = lambda r: int(r["tx_bytes"]) + int(r["rx_bytes"])
J = lambda r: int(r["transactions"])
names = ("vector", "dot", "scan", "matvec", "conv")
label = {"vector": "vector", "dot": "dot", "scan": "scan", "matvec": "matvec", "conv": "conv"}

# ---- latency model: T = B*tb + J*tau, ratio v3/v2 and break-even tau -------
taus = [10 ** (e / 8) for e in range(-48, -7)]          # 1 us .. 0.1 s
lines = ["tau_us," + ",".join(names)]
for tau in taus:
    cells = []
    for w in names:
        v2, v3 = wire[w, 2], wire[w, 3]
        cells.append(f"{(B(v3)*TB + J(v3)*tau) / (B(v2)*TB + J(v2)*tau):.6f}")
    lines.append(f"{tau*1e6:.4f}," + ",".join(cells))
(out / "latency-ratio.csv").write_text("\n".join(lines) + "\n")
breakeven = {}
for w in names:
    v2, v3 = wire[w, 2], wire[w, 3]
    dB, dJ = B(v3) - B(v2), J(v2) - J(v3)
    breakeven[w] = dB * TB / dJ if dB > 0 else 0.0   # v3 faster iff tau > this

# ---- roofline: useful arithmetic operations per wire byte -------------------
# Operations counted as one per multiplication and one per addition that the
# scalar reference needs (multiply-accumulate = 2), independent of the mapping.
ops = {"vector": 256, "dot": 2 * 256 - 1, "scan": 255,
       "matvec": 32 * 32 + 32 * 31, "conv": 64 * 5 + (64 * 5 - 68)}
pts = ["workload,intensity,attainable,protocol"]
for w in names:
    for v in (2, 3):
        i = ops[w] / B(wire[w, v])
        pts.append(f"{label[w]},{i:.6g},{min(PEAK, i*LINK):.6g},v{v}")
for k in (1, 64):
    r = scal["repeat", "4x4", "dot", "blocks", 256, k]
    i = k * ops["dot"] / B(r)
    pts.append(f"resident r={k},{i:.6g},{min(PEAK, i*LINK):.6g},blocks")
(out / "roofline-points.csv").write_text("\n".join(pts) + "\n")
for proto, name in (("v3", "roofline-v3.csv"), ("blocks", "roofline-blocks.csv")):
    (out / name).write_text("\n".join([pts[0]] + [p for p in pts[1:] if p.endswith("," + proto)]) + "\n")
grid = [10 ** (e / 4) for e in range(-8, 25)]
(out / "roofline-ceiling.csv").write_text(
    "intensity,uart,fast\n" + "\n".join(
        f"{i:.6g},{min(PEAK, i*LINK):.6g},{min(PEAK, i*100*LINK):.6g}" for i in grid) + "\n")

# ---- PE utilisation of each mapping for the five 16-PE shapes --------------
# Fraction of PEs doing useful arithmetic per step on a full tile:
#   diagonal L/RC with L=min(R,C); matvec and scan C/RC = 1/R; dot 1/RC.
shapes = ((1, 16), (2, 8), (4, 4), (8, 2), (16, 1))
u = ["shape,diagonal,matvec,scan,dot"]
for R, C in shapes:
    P = R * C
    u.append(f"{R}x{C},{min(R, C)/P:.6f},{C/P:.6f},{C/P:.6f},{1/P:.6f}")
(out / "utilization.csv").write_text("\n".join(u) + "\n")

us = lambda s: f"{s*1e6:.0f}"
gap = PEAK / max(min(PEAK, float(p.split(',')[2])) for p in pts[1:])
macros = [
    "% generated by tools/model_data.py (model values, not measurements)",
    f"\\newcommand{{\\ByteTimeUs}}{{{TB*1e6:.1f}}}",
    f"\\newcommand{{\\BreakEvenDot}}{{{us(breakeven['dot'])}}}",
    f"\\newcommand{{\\BreakEvenMatvec}}{{{us(breakeven['matvec'])}}}",
    f"\\newcommand{{\\BreakEvenConv}}{{{us(breakeven['conv'])}}}",
    f"\\newcommand{{\\LinkBytesPerSec}}{{{LINK:,.0f}}}".replace(",", "\\,"),
    f"\\newcommand{{\\PeakMops}}{{{PEAK/1e6:.0f}}}",
    f"\\newcommand{{\\RidgeIntensity}}{{{PEAK/LINK:,.0f}}}".replace(",", "\\,"),
    f"\\newcommand{{\\RooflineGapExp}}{{{math.floor(math.log10(gap))}}}",
]
(out / "model-macros.tex").write_text("\n".join(macros) + "\n")
